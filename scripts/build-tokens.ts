/**
 * Compiles src/design/tokens.ts → src/styles/tokens.css.
 * Run with `npm run tokens` (also runs before dev/build).
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import {
  bezierCss,
  durations,
  easings,
  ergonomics,
  fluidClamp,
  fonts,
  glows,
  layout,
  ndvi,
  palette,
  posterType,
  radii,
  spring,
  stagger,
  sunTypeFloor,
  surfaces,
  typeScale,
  zIndex,
} from '../src/design/tokens';

const kebab = (s: string) =>
  s
    .replace(/([a-z])([0-9])/g, '$1-$2')
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .toLowerCase();

const px = (n: number) => (n === 0 ? '0' : `${n / 16}rem`);
const indent = (lines: string[], n = 2) => lines.map((l) => (l ? ' '.repeat(n) + l : l)).join('\n');

const semanticVars = (surface: keyof typeof surfaces) =>
  Object.entries(surfaces[surface]).map(([k, v]) => `--${kebab(k)}: ${v};`);

const colorKeys = Object.keys(surfaces.paper).filter((k) => !k.startsWith('elev'));

const ndviStops = ndvi.stops.map((s) => `${s.hex} ${Math.round(s.at * 100)}%`).join(', ');

const out: string[] = [];

out.push(`/*
 * AUTO-GENERATED by scripts/build-tokens.ts from src/design/tokens.ts.
 * Do not edit by hand — change the tokens and run \`npm run tokens\`.
 */`);

/* ── @theme static: the closed scales. Tailwind defaults are reset, so only
   these values exist in the codebase. ── */
out.push(`@theme static {
${indent([
  '--color-*: initial;',
  ...Object.entries(palette).map(([k, v]) => `--color-${k}: ${v.hex};`),
  '--color-white: #ffffff;',
  '--color-black: #000000;',
  '',
  '--text-*: initial;',
  ...typeScale.flatMap((s) => {
    const lines = [`--text-${s.name}: ${fluidClamp(s.min, s.max)};`, `--text-${s.name}--line-height: ${s.leading};`];
    if (s.tracking !== '0') lines.push(`--text-${s.name}--letter-spacing: ${s.tracking};`);
    return lines;
  }),
  `--text-${posterType.name}: ${fluidClamp(posterType.min, posterType.max)};`,
  `--text-${posterType.name}--line-height: ${posterType.leading};`,
  `--text-${posterType.name}--letter-spacing: ${posterType.tracking};`,
  '',
  '--radius-*: initial;',
  ...Object.entries(radii).map(([k, v]) => `--radius-${k}: ${v.px === 9999 ? '9999px' : px(v.px)};`),
  '',
  '--shadow-*: initial;',
  '--ease-*: initial;',
  ...Object.entries(easings).map(([k, v]) => `--ease-${k}: ${bezierCss(v.bezier)};`),
  `--ease-spring: ${spring.css};`,
  '',
  "/* Tailwind's bare transition utilities use these: keep them on-token. */",
  `--default-transition-duration: ${durations.fast.ms}ms;`,
  `--default-transition-timing-function: ${bezierCss(easings['out-quint'].bezier)};`,
])}
}`);

/* ── @theme inline: utilities that resolve to runtime (surface-aware) vars ── */
out.push(`@theme inline {
${indent([
  ...colorKeys.map((k) => `--color-${kebab(k)}: var(--${kebab(k)});`),
  '',
  `--font-display: var(${fonts.display.variable}), '${fonts.display.family}', ${fonts.display.fallback};`,
  `--font-sans: var(${fonts.sans.variable}), '${fonts.sans.family}', ${fonts.sans.fallback};`,
  `--font-mono: var(${fonts.mono.variable}), '${fonts.mono.family}', var(${fonts.sans.variable}), ${fonts.mono.fallback};`,
  '',
  '--shadow-raised: var(--elev-raised);',
  '--shadow-float: var(--elev-float);',
  '--shadow-overlay: var(--elev-overlay);',
  '--shadow-inset: var(--elev-inset);',
  `--shadow-glow-sprout: ${glows.sprout};`,
  `--shadow-glow-water: ${glows.water};`,
])}
}`);

/* ── :root — static runtime tokens + paper (default) surface ── */
const d = ergonomics.default;
const s = ergonomics.sun;
out.push(`:root {
${indent([
  ...Object.entries(durations).map(([k, v]) => `--dur-${k}: ${v.ms}ms;`),
  `--dur-spring: ${spring.durationMs}ms;`,
  `--stagger-step: ${stagger.stepMs}ms;`,
  '',
  ...Object.entries(zIndex).map(([k, v]) => `--z-${k}: ${v};`),
  '',
  `--target: ${px(d.target)};`,
  `--target-lg: ${px(d.targetLg)};`,
  `--bw: ${d.borderWidth}px;`,
  `--focus-w: ${d.focusWidth}px;`,
  `--focus-offset: ${d.focusOffset}px;`,
  '',
  `--max-w: ${layout.maxWidth}px;`,
  `--page-margin: ${layout.grid[0].margin}px;`,
  `--gutter: ${layout.grid[0].gutter}px;`,
  `--section-y: ${layout.section.mobile}px;`,
  '',
  `--glow-sprout: ${glows.sprout};`,
  `--glow-water: ${glows.water};`,
  `--ndvi-stops: ${ndviStops};`,
  '/* RTL: low NDVI sits at inline-start (right) and grows toward inline-end. */',
  `--ndvi-inline: linear-gradient(to left, var(--ndvi-stops));`,
  `--ndvi-up: linear-gradient(to top, var(--ndvi-stops));`,
  '',
  ...semanticVars('paper'),
])}
}`);

out.push(`@supports (background: linear-gradient(in oklch, red, blue)) {
  :root {
    --ndvi-inline: linear-gradient(to left in oklch, var(--ndvi-stops));
    --ndvi-up: linear-gradient(to top in oklch, var(--ndvi-stops));
  }
}`);

for (const g of layout.grid.slice(1)) {
  const section =
    g.from >= 1024 ? layout.section.desktop : g.from >= 640 ? layout.section.tablet : layout.section.mobile;
  out.push(`@media (min-width: ${g.from}px) {
  :root {
    --page-margin: ${g.margin}px;
    --gutter: ${g.gutter}px;
    --section-y: ${section}px;
  }
}`);
}

/* ── Surfaces ── */
out.push(`[data-surface='paper'] {
${indent([...semanticVars('paper'), 'color-scheme: light;'])}
}`);
out.push(`[data-surface='soil'] {
${indent([...semanticVars('soil'), 'color-scheme: dark;'])}
}`);

/* ── מצב שמש — overrides every surface, raises targets and type floors ── */
out.push(`:root[data-theme='sun'],
:root[data-theme='sun'] [data-surface] {
${indent([...semanticVars('sun'), 'color-scheme: light;'])}
}`);
out.push(`:root[data-theme='sun'] {
${indent([
  `--target: ${px(s.target)};`,
  `--target-lg: ${px(s.targetLg)};`,
  `--bw: ${s.borderWidth}px;`,
  `--focus-w: ${s.focusWidth}px;`,
  `--focus-offset: ${s.focusOffset}px;`,
  ...Object.entries(sunTypeFloor).map(([name, v]) => `--text-${name}: ${fluidClamp(v![0], v![1])};`),
])}
}`);

/* ── Reduced motion: durations collapse, nothing travels ── */
out.push(`@media (prefers-reduced-motion: reduce) {
  :root {
${indent([...Object.keys(durations).map((k) => `--dur-${k}: 1ms;`), '--dur-spring: 1ms;', '--stagger-step: 0ms;'], 4)}
  }
}`);

const target = resolve(__dirname, '../src/styles/tokens.css');
writeFileSync(target, out.join('\n\n') + '\n');
console.log(`tokens → ${target}`);
